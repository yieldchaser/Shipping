"""Ledger of everything removed from data/extracted/md since a date: per commit, per source, lines
removed / added and whole files deleted, with the commit subject (the reason). Nothing in git is ever
lost: restore any file as it was before a commit with  git show <sha>^:<path> > <path>.

    python scripts/audit/deletion_ledger.py [--since 2026-10-09] [--out docs/handoff/DELETION_LEDGER.md]
"""
import argparse
import collections
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

ap = argparse.ArgumentParser()
ap.add_argument("--since", default="2026-10-09")
ap.add_argument("--out", default="docs/handoff/DELETION_LEDGER.md")
a = ap.parse_args()

log = subprocess.run(["git", "log", "--no-merges", f"--since={a.since}", "--numstat", "--format=@@%h|%ad|%s",
                      "--date=short", "--", "data/extracted/md"], cwd=ROOT, capture_output=True, text=True,
                     encoding="utf-8").stdout
deleted = subprocess.run(["git", "log", "--no-merges", f"--since={a.since}", "--diff-filter=D", "--name-only",
                          "--format=@@%h", "--", "data/extracted/md"], cwd=ROOT, capture_output=True, text=True,
                         encoding="utf-8").stdout
dfiles = collections.Counter()
cur = None
for line in deleted.splitlines():
    if line.startswith("@@"):
        cur = line[2:]
    elif line.endswith(".md") and cur:
        dfiles[(cur, line.split("/")[3])] += 1

rows, cur = [], None
for line in log.splitlines():
    if line.startswith("@@"):
        sha, date, subj = line[2:].split("|", 2)
        cur = {"sha": sha, "date": date, "subj": subj, "src": collections.Counter(), "add": collections.Counter()}
        rows.append(cur)
    elif line.strip() and cur:
        ad, rm, path = line.split("\t", 2)
        if ad == "-" or not path.endswith(".md"):
            continue
        src = path.split("/")[3]
        cur["src"][src] += int(rm)
        cur["add"][src] += int(ad)

out = ["# Deletion ledger — data/extracted/md since " + a.since, "",
       "Every line below is recoverable: `git show <sha>^:<path>` prints the file as it was before that "
       "commit. Generated by scripts/audit/deletion_ledger.py.", "",
       "| commit | date | source | lines removed | lines added | files deleted | reason (commit subject) |",
       "|---|---|---|---:|---:|---:|---|"]
tot = collections.Counter()
for r in rows:
    for src, rm in r["src"].most_common():
        if rm == 0:
            continue
        tot[src] += rm
        out.append(f"| {r['sha']} | {r['date']} | {src} | {rm} | {r['add'][src]} | "
                   f"{dfiles.get((r['sha'], src), 0)} | {r['subj'][:110].replace('|', '/')} |")
out += ["", "## Totals by source (lines removed)", ""] + [f"- {s}: {n}" for s, n in tot.most_common()]
(ROOT / a.out).write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{len(rows)} commits, {sum(tot.values())} lines removed -> {a.out}")
